def inventory_hlc():
    db = sqlite3.connect((ROOT / 'processed_data/v1/lstsr_tb/index.sqlite').as_uri() + '?mode=ro&immutable=1', uri=True)
    signatures = {}
    for (text,) in db.execute('select loc from records'):
        loc = json.loads(text)
        for kind in ['lst', 'hls']:
            signatures[loc[kind]] = loc['source_signatures'][kind]
    db.close()
    result = []
    found = set()
    for directory, dirs, files in os.walk(ROOT / HLC_SOURCE):
        dirs.sort()
        for name in sorted(files):
            p = Path(directory) / name
            stat = p.stat()
            relative = p.relative_to(ROOT / HLC_SOURCE).as_posix()
            if relative in signatures:
                expected = signatures[relative]
                if (stat.st_size, stat.st_mtime_ns) != (expected['size'], expected['mtime_ns']):
                    raise ValueError(f'Frozen source changed: {p}')
                found.add(relative)
            result.append({'path': p.relative_to(ROOT).as_posix(), 'size': stat.st_size, 'mtime_ns': stat.st_mtime_ns})
    if found != signatures.keys() or len(found) != 555616:
        raise ValueError('HLC source membership is incomplete')
    save(OUT / 'hlc_inventory_summary.json', {'files': len(result), 'bytes': sum(x['size'] for x in result), 'frozen_source_signatures_verified': len(found)})
    return result


class HashStream:
    def __init__(self, stream):
        self.stream = stream
        self.hash = hashlib.sha256()
    def read(self, size=-1):
        data = self.stream.read(size)
        self.hash.update(data)
        return data
    def write(self, data):
        self.hash.update(data)
        return self.stream.write(data)
    def tell(self):
        return self.stream.tell()
    def flush(self):
        self.stream.flush()


def pack_hlc(stage, inventory, shard_bytes):
    groups, batch, size = [], [], 0
    for row in inventory:
        if batch and size + row['size'] > shard_bytes:
            groups.append(batch)
            batch, size = [], 0
        batch.append(row)
        size += row['size']
    if batch:
        groups.append(batch)
    shards = []
    for index, batch in enumerate(groups):
        relative = f'data/part-{index:05d}.tar'
        member_relative = f'checksums/part-{index:05d}.members.jsonl'
        path, members = stage / relative, stage / member_relative
        receipt = OUT / 'shards' / f'{index:05d}.json'
        signature = hashlib.sha256(json.dumps(batch, sort_keys=True).encode()).hexdigest()
        if receipt.exists():
            done = json.loads(receipt.read_text())
            if done['inventory_sha256'] != signature:
                raise ValueError(f'Stale or damaged shard receipt: {receipt}')
            uploaded = OUT / 'hlc_uploaded_shards' / receipt.name
            # Receipts are reused only with a local manifest. After migration from
            # an unavailable drive, rebuild missing manifests from original bytes.
            if members.exists() and sha(members) == done['members_sha256']:
                already_remote = uploaded.exists() and json.loads(uploaded.read_text())['sha256'] == done['sha256']
                if already_remote or (path.exists() and path.stat().st_size == done['size'] and sha(path) == done['sha256']):
                    print(f'Checked existing HLC shard {index + 1}/{len(groups)}', flush=True)
                    shards.append(done)
                    continue
        # At most four generated shards on disk; uploader removes only verified
        # temporary tar files. Keep all member manifests and original source data.
        while len(list((stage / 'data').glob('*.tar'))) >= 4:
            time.sleep(10)
        path.parent.mkdir(parents=True, exist_ok=True)
        members.parent.mkdir(parents=True, exist_ok=True)
        temporary = path.with_suffix('.tar.partial')
        temporary_members = members.with_suffix('.jsonl.partial')
        with temporary.open('wb') as raw, temporary_members.open('w', encoding='utf-8', newline='\n') as manifest:
            output = HashStream(raw)
            with tarfile.open(fileobj=output, mode='w|', format=tarfile.PAX_FORMAT) as archive:
                for row in batch:
                    source = ROOT / row['path']
                    stat = source.stat()
                    if (stat.st_size, stat.st_mtime_ns) != (row['size'], row['mtime_ns']):
                        raise ValueError(f'Source changed during packing: {source}')
                    info = tarfile.TarInfo(row['path'])
                    info.size = row['size']
                    info.mode = 0o644
                    info.mtime = row['mtime_ns'] // 10**9
                    info.pax_headers = {'hf.mtime_ns': str(row['mtime_ns'])}
                    with source.open('rb') as raw_source:
                        hashed = HashStream(raw_source)
                        archive.addfile(info, hashed)
                    after = source.stat()
                    if (after.st_size, after.st_mtime_ns) != (row['size'], row['mtime_ns']):
                        raise ValueError(f'Source changed while reading: {source}')
                    manifest.write(json.dumps({**row, 'sha256': hashed.hash.hexdigest()}, separators=(',', ':')) + '\n')
            output.flush()
            archive_hash = output.hash.hexdigest()
        archive_stat = temporary.stat()
        temporary.replace(path)
        temporary_members.replace(members)
        done = {'path': relative, 'size': archive_stat.st_size, 'mtime_ns': archive_stat.st_mtime_ns, 'sha256': archive_hash,
                'members': member_relative, 'members_sha256': sha(members),
                'files': len(batch), 'inventory_sha256': signature}
        save(receipt, done)
        shards.append(done)
        status = {'phase': 'packing_hlc', 'complete_shards': index + 1, 'total_shards': len(groups),
                  'packed_bytes': sum(x['size'] for x in shards), 'updated_unix': time.time()}
        save(OUT / 'status.json', status)
        print(json.dumps(status), flush=True)
    return shards


def finalize(dataset, stage, shards=None):
    known = {x['path']: x['sha256'] for x in (shards or [])}
    if dataset == 'HLP':
        original = ROOT / 'artifacts/prithvi_data_v1_20260909.zip'
        dest = stage / 'artifacts' / original.name
        dest.parent.mkdir(exist_ok=True)
        if not dest.exists():
            os.link(original, dest)  # same-volume staging, no second 116 GiB copy
        expected = json.loads(original.with_suffix('.zip.verification.json').read_text())
        actual = sha(dest)
        if actual != expected['sha256']:
            raise ValueError('HLP archive checksum mismatch')
        known[dest.relative_to(stage).as_posix()] = actual
    files = []
    for path in sorted(stage.rglob('*')):
        if not path.is_file() or path.name == 'release.json' or '.cache' in path.parts:
            continue
        if path.name.endswith(('.partial', '.tmp', '-wal', '-shm', '.pyc')) or '__pycache__' in path.parts:
            continue
        rel = path.relative_to(stage).as_posix()
        if rel.startswith('data/') and dataset == 'HLC':
            continue  # Shard inventory comes from durable receipts, even after local cleanup.
        stat = path.stat()
        files.append({'path': rel, 'size': stat.st_size, 'mtime_ns': stat.st_mtime_ns,
                      'sha256': known[rel] if rel in known else sha(path)})
    present = {item['path'] for item in files}
    for shard in shards or []:
        if shard['path'] not in present:
            files.append({k: shard[k] for k in ('path', 'size', 'mtime_ns', 'sha256')})
    release = {'dataset': dataset, 'version': 'lossless-hub-v1-20261005', 'status': 'packaged',
               'array_conversion': False, 'files': files, 'total_bytes': sum(x['size'] for x in files),
               'shards': shards or []}
    save(stage / 'release.json', release)
    save(OUT / f'{dataset.lower()}_release_receipt.json', {'stage': str(stage), 'release_sha256': sha(stage / 'release.json'),
         'total_bytes': release['total_bytes'], 'files': len(files), 'status': 'packaged'})
    print(f'{dataset}: packaged {len(files)} files, {release["total_bytes"]} bytes', flush=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--metadata-only', action='store_true')
    parser.add_argument('--dataset', choices=['HLP', 'HLC', 'both'], default='both')
    parser.add_argument('--hlc-stage', type=Path, default=DEFAULT_HLC)
    args = parser.parse_args()
    stages = {'HLP': OUT / 'HLS-LST-Pairs', 'HLC': args.hlc_stage}
    for dataset, stage in stages.items():
        if args.dataset not in [dataset, 'both']:
            continue
        metadata(dataset, stage)
        if args.metadata_only:
            continue
        if dataset == 'HLP':
            finalize(dataset, stage)
        else:
            inventory = inventory_hlc()
            required = 24 * 1024**3
            if shutil.disk_usage(stage).free < required:
                raise ValueError('Insufficient staging disk space')
            shards = pack_hlc(stage, inventory, 4 * 1024**3)
            finalize(dataset, stage, shards)
    save(OUT / 'status.json', {'phase': 'metadata_ready' if args.metadata_only else 'packaged', 'updated_unix': time.time()})


if __name__ == '__main__':
    main()
